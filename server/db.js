export function semAcento(texto) {
  return String(texto ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase();
}

export function somenteDigitos(texto) {
  return String(texto ?? '').replace(/\D/g, '');
}

