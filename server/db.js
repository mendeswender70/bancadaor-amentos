const ehPostgres = (v) => /^postgres(ql)?:\/\/.+/.test(v || '');

/**
 * Descobre o banco a usar. Aceita DATABASE_URL, POSTGRES_URL (criada pela
 * integração Supabase ↔ Vercel) ou qualquer *_URL com um endereço
 * postgres://, preferindo a conexão com pooler ("NON_POOLING" fica por último).
 * Sem nenhuma, usa um Postgres embutido (PGlite) na pasta data/.
 */
export function configuracaoBanco(env = process.env) {
  for (const chave of ['DATABASE_URL', 'POSTGRES_URL', 'SUPABASE_DB_URL']) {
    if (ehPostgres(env[chave])) return { url: env[chave] };
  }
  const candidatas = Object.entries(env)
    .filter(([chave, valor]) => /_URL$/.test(chave) && ehPostgres(valor))
    .sort(([a], [b]) => Number(/NON_POOLING/.test(a)) - Number(/NON_POOLING/.test(b)));
  return candidatas.length ? { url: candidatas[0][1] } : null;
}

/** Troca "?" por $1, $2… (ignorando o que estiver entre aspas simples). */
export function converterParametros(sql) {
  let n = 0;
  let resultado = '';
  let emTexto = false;
  for (const c of sql) {
    if (c === "'") emTexto = !emTexto;
    resultado += !emTexto && c === '?' ? `$${++n}` : c;
  }
  return resultado;
}

function normalizarLinha(linha) {
  const obj = {};
  for (const [k, v] of Object.entries(linha)) obj[k] = v instanceof Date ? v.toISOString() : v;
  return obj;
}

const argumentos = (params) =>
  params.map((p) => (p === undefined ? null : typeof p === 'boolean' ? (p ? 1 : 0) : p));

/**
 * Camada fina sobre o driver, com o jeito de uso do resto do código:
 * get/all/run com parâmetros "?" e transacao(fn).
 */
class Banco {
  /** @param {{consultar: Function, transacao?: Function, fechar?: Function}} driver */
  constructor(driver) {
    this.driver = driver;
  }

  async all(sql, ...params) {
    const { linhas } = await this.driver.consultar(converterParametros(sql), argumentos(params));
    return linhas.map(normalizarLinha);
  }

  async get(sql, ...params) {
    return (await this.all(sql, ...params))[0];
  }

  /** Para INSERT com "RETURNING id", devolve o id em lastInsertRowid. */
  async run(sql, ...params) {
    const { linhas, alteradas } = await this.driver.consultar(converterParametros(sql), argumentos(params));
    return { changes: alteradas, lastInsertRowid: linhas[0]?.id };
  }

  /** Executa `fn(transacao)` de forma atômica. Dentro dela, use só o objeto recebido. */
  async transacao(fn) {
    if (!this.driver.transacao) return fn(this);
    return this.driver.transacao((driverTx) => fn(new Banco(driverTx)));
  }

  async close() {
    await this.driver.fechar?.();
  }
}

function driverPostgres(url) {
  // Parâmetros da URL (sslmode, supa…) são tratados aqui, não repassados ao servidor.
  const endereco = new URL(url);
  const local = ['localhost', '127.0.0.1', '[::1]'].includes(endereco.hostname);
  const semSsl = local || endereco.searchParams.get('sslmode') === 'disable';
  endereco.search = '';
  const sql = postgres(endereco.toString(), {
    ssl: semSsl ? false : 'require',
    prepare: false, // obrigatório no pooler do Supabase (modo transação)
    max: 5,
    idle_timeout: 20,
    connect_timeout: 15,
    onnotice: () => {},
    // bigint (valores em centavos) e numeric (SUM) voltam como número
    types: { numero: { to: 20, from: [20, 1700], serialize: (x) => String(x), parse: (x) => Number(x) } },
  });
  const consultor = (exec) => async (texto, params) => {
    const r = await exec.unsafe(texto, params);
    return { linhas: [...r], alteradas: r.count ?? 0 };
  };
  return {
    consultar: consultor(sql),
    transacao: (fn) => sql.begin((tx) => fn({ consultar: consultor(tx) })),
    fechar: () => sql.end({ timeout: 5 }),
  };
}

async function driverEmbutido(pasta) {
  // Carregado só no computador e nos testes; o nome em variável evita que a
  // Vercel empacote o PGlite junto da função.
  const modulo = '@electric-sql/pglite';
  const { PGlite } = await import(modulo);
  if (pasta !== 'memory://') mkdirSync(pasta, { recursive: true });
  const db = new PGlite(pasta, { parsers: { 20: Number, 1700: Number } });
  const consultor = (exec) => async (texto, params) => {
    const r = await exec.query(texto, params);
    return { linhas: r.rows, alteradas: r.affectedRows ?? 0 };
  };
  return {
    pglite: db,
    consultar: consultor(db),
    transacao: (fn) => db.transaction((tx) => fn({ consultar: consultor(tx) })),
    fechar: () => db.close(),
  };
}

async function migrar(banco) {
  await banco.run(
    'CREATE TABLE IF NOT EXISTS migracoes (versao integer PRIMARY KEY, aplicada_em timestamptz NOT NULL DEFAULT now())',
  );
  await banco.run('ALTER TABLE migracoes ENABLE ROW LEVEL SECURITY');
  const versaoAtual = async (b) => (await b.get('SELECT COALESCE(MAX(versao), 0) AS v FROM migracoes')).v;
  if ((await versaoAtual(banco)) >= MIGRACOES.length) return;
  await banco.transacao(async (t) => {
    // Impede que duas instâncias apliquem a mesma migração ao mesmo tempo.
    await t.run('SELECT pg_advisory_xact_lock(7240531)');
    for (let v = await versaoAtual(t); v < MIGRACOES.length; v++) {
      for (const comando of MIGRACOES[v]) await t.run(comando);
      await t.run('INSERT INTO migracoes (versao) VALUES (?)', v + 1);
    }
  });
}

/**
 * Traduz falhas de conexão em uma mensagem que diz o que corrigir na
 * DATABASE_URL — sem mostrar a senha.
 */
export function explicarErroBanco(erro) {
  const codigo = erro?.code || erro?.errno || '';
  const texto = String(erro?.message || '');
  const dica = 'Copie de novo em Supabase → Connect → Transaction pooler.';
  if (erro instanceof TypeError && /url/i.test(texto)) {
    return 'O endereço na DATABASE_URL está em formato inválido. Confira se tirou os colchetes [ ] da senha e se a senha tem só letras e números.';
  }
  if (codigo === '28P01' || /password authentication failed/i.test(texto)) {
    return 'A senha do banco na DATABASE_URL está incorreta. Gere uma nova em Supabase → Project Settings → Database → Reset database password e atualize a variável na Vercel.';
  }
  if (/tenant or user not found/i.test(texto)) {
    return `O usuário na DATABASE_URL está incorreto (ele deve ser "postgres.<código do projeto>"). ${dica}`;
  }
  if (['ENOTFOUND', 'EAI_AGAIN'].includes(codigo)) return `O endereço do banco na DATABASE_URL não foi encontrado. ${dica}`;
  if (['ENETUNREACH', 'EHOSTUNREACH', 'EADDRNOTAVAIL'].includes(codigo)) {
    return 'Não foi possível alcançar o banco. Use o endereço do "Transaction pooler" (porta 6543), não o "Direct connection".';
  }
  if (codigo === 'ECONNREFUSED') return `O banco recusou a conexão. Confira a porta (6543) na DATABASE_URL. ${dica}`;
  if (codigo === 'CONNECT_TIMEOUT' || codigo === 'ETIMEDOUT') return 'O banco demorou demais para responder. Tente de novo em instantes.';
  return `Não foi possível conectar ao banco de dados${codigo ? ` (${codigo})` : ''}. ${dica}`;
}

/**
 * Abre o banco e aplica as migrações.
 * @param {{url: string}|null} [config] sem config: detecta pelo ambiente.
 *   url "memory://" ou "pglite:<pasta>" usam o Postgres embutido.
 */
export async function abrirBanco(config = configuracaoBanco()) {
  let driver;
  const url = config?.url;
  if (url && ehPostgres(url)) {
    try {
      driver = driverPostgres(url);
    } catch (erro) {
      throw new ErroHttp(503, explicarErroBanco(erro));
    }
  } else if (url === 'memory://' || url?.startsWith('pglite:')) {
    driver = await driverEmbutido(url === 'memory://' ? url : url.slice('pglite:'.length));
  } else {
    if (process.env.VERCEL) {
      throw new ErroHttp(
        503,
        'Banco de dados não configurado. Na Vercel, crie a variável DATABASE_URL com o endereço do banco Supabase e faça um novo deploy.',
      );
    }
    driver = await driverEmbutido(fileURLToPath(new URL('../data/pglite', import.meta.url)));
  }
  const banco = new Banco(driver);
  try {
    await migrar(banco);
  } catch (erro) {
    await banco.close().catch(() => {});
    console.error('Falha ao conectar no banco:', erro?.code || '', erro?.message || erro);
    throw new ErroHttp(503, explicarErroBanco(erro));
  }
  return banco;
}
